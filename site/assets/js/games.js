/* GeekDeal — renderer for automated game deals and articles.
   Reads window.GD_GAMES / window.GD_ARTICLES (generated by automation/publish.py). */
(function () {
  'use strict';

  var state = { store: 'all', sort: 'score' };

  function money(amount, currency) {
    try {
      return new Intl.NumberFormat('en-US', {
        style: 'currency', currency: currency || 'USD',
        minimumFractionDigits: amount % 1 === 0 ? 0 : 2,
        maximumFractionDigits: 2
      }).format(amount);
    } catch (e) {
      return '$' + Number(amount).toFixed(2);
    }
  }

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function fmtDate(iso) {
    if (!iso) return '';
    try {
      return new Date(iso).toLocaleString('en-US', {
        month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit',
        timeZone: 'America/New_York', timeZoneName: 'short'
      });
    } catch (e) { return iso; }
  }

  function sparkline(points, w, h) {
    var pts = (points || []).filter(function (p) { return typeof p === 'number'; });
    if (pts.length < 2) return '';
    var lo = Math.min.apply(null, pts), hi = Math.max.apply(null, pts);
    var span = (hi - lo) || 1, pad = 3;
    var step = (w - pad * 2) / (pts.length - 1);
    var coords = pts.map(function (p, i) {
      return [(pad + i * step).toFixed(1), (pad + (1 - (p - lo) / span) * (h - pad * 2)).toFixed(1)];
    });
    var line = coords.map(function (c) { return c[0] + ',' + c[1]; }).join(' ');
    var area = pad + ',' + (h - pad) + ' ' + line + ' ' + (w - pad) + ',' + (h - pad);
    var last = coords[coords.length - 1];
    return '<svg class="spark" viewBox="0 0 ' + w + ' ' + h + '" width="' + w + '" height="' + h +
      '" aria-hidden="true"><polygon points="' + area + '" fill="rgba(52,211,153,.12)"/>' +
      '<polyline points="' + line + '" fill="none" stroke="#34d399" stroke-width="2" ' +
      'stroke-linejoin="round" stroke-linecap="round"/>' +
      '<circle cx="' + last[0] + '" cy="' + last[1] + '" r="2.5" fill="#34d399"/></svg>';
  }

  function fmtDay(iso) {
    if (!iso) return '';
    try {
      return new Date(iso).toLocaleDateString('en-US', {
        month: 'short', day: 'numeric', year: 'numeric', timeZone: 'America/New_York'
      });
    } catch (e) { return ''; }
  }

  function base(grid) {
    return grid.getAttribute('data-base') || '';
  }

  function card(d, b) {
    var pct = d.discountPct || Math.round((1 - d.price / d.referencePrice) * 100);
    var article = d.articleSlug
      ? '<a class="g-read" href="' + b + 'deals/' + esc(d.articleSlug) + '.html">' + (d.pageKind === 'landing' ? 'Price history' : 'Read') + '</a>'
      : '';
    return '' +
      '<article class="deal game-card">' +
        '<div class="deal-media">' +
          '<img src="' + esc(d.image) + '" alt="' + esc(d.title) + '" loading="lazy" ' +
               'onerror="this.src=\'https://images.unsplash.com/photo-1550745165-9bc0b252726f?w=800&q=80\'">' +
          '<span class="discount">−' + pct + '%</span>' +
          '<span class="g-score">Deal score <b>' + Math.round(d.score || 0) + '</b></span>' +
          (d.showLowBadge ? '<span class="g-low" title="Lowest price recorded since we started tracking">' +
            (d.lowest30d ? 'Lowest in 30 days' : 'Lowest tracked') + '</span>' : '') +
        '</div>' +
        '<div class="deal-body">' +
          '<span class="deal-store">' + esc(d.store) + ' · <span class="g-platform">' + esc(d.platform || 'PC') + '</span></span>' +
          '<h3 class="deal-title">' + esc(d.title) + '</h3>' +
          '<div class="price-row">' +
            '<span class="price-now">' + money(d.price, d.currency) + '</span>' +
            '<span class="price-was">' + money(d.referencePrice, d.currency) + '</span>' +
            '<span class="price-note">Verified ' + esc(fmtDate(d.verifiedAt)) + '</span>' +
          '</div>' +
          historyRow(d) +
          '<div class="g-actions">' +
            '<a class="deal-cta" href="' + esc(d.url) + '" target="_blank" rel="nofollow sponsored noopener" data-deal-id="' + esc(d.id) + '" data-store="' + esc(d.store) + '">See deal →</a>' +
            article +
          '</div>' +
          '<div class="deal-foot"><span>' + (d.affiliateTagged ? 'Affiliate link' : 'Direct store link') + ' · price may change</span></div>' +
        '</div>' +
      '</article>';
  }

  function historyRow(d) {
    if (!d.lowestPrice && !(d.spark && d.spark.length > 1)) return '';
    var spark = sparkline(d.spark, 150, 30);
    var low = d.lowestPrice != null
      ? 'Low ' + money(d.lowestPrice, d.currency)
      : '';
    var since = d.trackedSince ? 'tracked since ' + fmtDay(d.trackedSince) : '';
    var n = d.observations ? d.observations + (d.observations === 1 ? ' check' : ' checks') : '';
    return '<div class="g-history">' + spark +
      '<div class="g-history-txt"><span>' + esc(low) + '</span><span>' +
      esc([n, since].filter(Boolean).join(' \u00b7 ')) + '</span></div></div>';
  }

  var SORTS = {
    score: function (a, b) { return (b.score || 0) - (a.score || 0); },
    discount: function (a, b) { return (b.discountPct || 0) - (a.discountPct || 0); },
    price: function (a, b) { return (a.price || 0) - (b.price || 0); },
    lowest: function (a, b) {
      var la = (a.lowest30d || a.showLowBadge) ? 1 : 0, lb = (b.lowest30d || b.showLowBadge) ? 1 : 0;
      return (lb - la) || ((b.score || 0) - (a.score || 0));
    }
  };

  function sortDeals(list, key) {
    var fn = SORTS[key] || SORTS.score;
    // stable sort: decorate with index so ties keep pipeline order
    return list.map(function (d, i) { return [d, i]; })
      .sort(function (x, y) { return fn(x[0], y[0]) || (x[1] - y[1]); })
      .map(function (p) { return p[0]; });
  }

  function initSort() {
    var sel = document.getElementById('deal-sort');
    if (!sel) return;
    sel.addEventListener('change', function () {
      state.sort = sel.value;
      Array.prototype.forEach.call(document.querySelectorAll('[data-game-grid]'), function (g) {
        renderGrid(g, true);
      });
    });
  }

  function renderGrid(grid, reset) {
    var all = window.GD_GAMES || [];
    if (state.store !== 'all') {
      all = all.filter(function (d) { return d.storeSlug === state.store; });
    }
    all = sortDeals(all, state.sort);
    var limit = parseInt(grid.getAttribute('data-limit') || '0', 10);
    if (limit > 0) all = all.slice(0, limit);

    var pageSize = parseInt(grid.getAttribute('data-page') || '0', 10);
    if (reset || !grid._shown) grid._shown = pageSize > 0 ? pageSize : all.length;
    var items = pageSize > 0 ? all.slice(0, grid._shown) : all;

    var b = base(grid);
    grid.innerHTML = items.length
      ? items.map(function (d) { return card(d, b); }).join('')
      : '<div class="empty">No live deals from this store right now \u2014 check back after the next refresh.</div>';

    if (grid._moreBtn) { grid._moreBtn.remove(); grid._moreBtn = null; }
    if (pageSize > 0 && all.length > items.length) {
      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'btn btn-ghost load-more';
      btn.textContent = 'Load more deals (' + (all.length - items.length) + ' left)';
      btn.addEventListener('click', function () {
        grid._shown += pageSize;
        renderGrid(grid);
      });
      grid.parentNode.insertBefore(btn, grid.nextSibling);
      grid._moreBtn = btn;
    }

    var count = document.getElementById('game-count');
    if (count) count.textContent = all.length + ' live deals';
  }

  function renderArticles(host) {
    var items = (window.GD_ARTICLES || []).slice();
    var limit = parseInt(host.getAttribute('data-limit') || '0', 10);
    if (limit > 0) items = items.slice(0, limit);
    var b = base(host);

    host.innerHTML = items.map(function (a) {
      return '' +
        '<article class="news-card">' +
          '<div class="thumb"><img src="' + esc(a.image) + '" alt="" loading="lazy"></div>' +
          '<div class="news-body">' +
            '<span class="news-cat">' + esc(a.store) + ' · −' + a.discountPct + '%</span>' +
            '<h3><a href="' + b + 'deals/' + esc(a.slug) + '.html">' + esc(a.title) + '</a></h3>' +
            '<p>' + esc(a.dek) + '</p>' +
            '<span class="news-date">' + esc(fmtDate(a.verifiedAt)) + '</span>' +
          '</div>' +
        '</article>';
    }).join('');
  }

  function initChips() {
    var chips = document.querySelectorAll('[data-store-filter]');
    if (!chips.length) return;
    Array.prototype.forEach.call(chips, function (chip) {
      chip.addEventListener('click', function () {
        Array.prototype.forEach.call(chips, function (c) { c.classList.remove('is-active'); });
        chip.classList.add('is-active');
        state.store = chip.getAttribute('data-store-filter');
        Array.prototype.forEach.call(document.querySelectorAll('[data-game-grid]'), function (g) {
          renderGrid(g, true);
        });
      });
    });
  }

  function init() {
    Array.prototype.forEach.call(document.querySelectorAll('[data-game-grid]'), renderGrid);
    Array.prototype.forEach.call(document.querySelectorAll('[data-article-grid]'), renderArticles);
    initChips();
    initSort();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
